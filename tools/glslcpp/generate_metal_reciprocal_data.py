#!/usr/bin/env python3
"""Embed the CPU authority's measured Metal reciprocal deviations in C++.

The authority's src/csl/metal-reciprocal-data.js holds the Apple M4 capture
that src/csl/metal-division.js reads: the band limits, the deviation counts,
the SHA-256 of the captured 2-bit table and the base64 band bitstream. This
tool copies those values, and every bitstream line byte for byte, into
src/metal_reciprocal_data.cpp. It refuses an authority module whose
SHA-256 differs from the pinned capture, so a new capture changes this file
only through a deliberate re-pin.

Usage:
  python3 -m tools.glslcpp.generate_metal_reciprocal_data --write --cpu-root <authority>
  python3 -m tools.glslcpp.generate_metal_reciprocal_data --check --cpu-root <authority>
  python3 -m tools.glslcpp.generate_metal_reciprocal_data --verify
"""
from __future__ import annotations

import argparse
import hashlib
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
TARGET = ROOT / "src/metal_reciprocal_data.cpp"
AUTHORITY_MODULE = "src/csl/metal-reciprocal-data.js"
# The authority's own test (test/metal-division.test.js) pins this LF digest.
AUTHORITY_MODULE_SHA256 = "08905259e72a066e77675f98b9700d6c3a6467662f5de562d8f8e1e14d082c87"
BASE64_LINE = re.compile(r"^[A-Za-z0-9+/=]+$")


class DataError(ValueError):
    pass


def _number(text: str, name: str) -> str:
    match = re.search(rf"^  {name}: ([0-9.]+),$", text, re.MULTILINE)
    if match is None:
        raise DataError(f"{AUTHORITY_MODULE} declares no {name}")
    return match.group(1)


def parse_module(text: str) -> dict:
    """The METAL_RECIPROCAL fields of the authority module."""
    bits = re.search(r"^  bits: `\n(.*?)`,\n\}\)\n?\Z", text, re.MULTILINE | re.DOTALL)
    table = re.search(r'^  tableSha256: "([0-9a-f]{64})",$', text, re.MULTILINE)
    if bits is None or table is None:
        raise DataError(f"{AUTHORITY_MODULE} has an unexpected layout")
    lines = bits.group(1).split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    if not lines or any(BASE64_LINE.fullmatch(line) is None for line in lines):
        raise DataError(f"{AUTHORITY_MODULE} bits are not base64 lines")
    band_low, band_high = float(_number(text, "bandLow")), float(_number(text, "bandHigh"))
    counts = {name: int(_number(text, name)) for name in ("bandBits", "positiveDeviations", "negativeDeviations")}
    return {
        "bandLow": band_low, "bandHigh": band_high, **counts,
        "tableSha256": table.group(1), "lines": lines,
        "bitsSha256": hashlib.sha256("".join(lines).encode("ascii")).hexdigest(),
    }


def render(data: dict) -> bytes:
    out = [
        "// Generated by tools/glslcpp/generate_metal_reciprocal_data.py. Do not edit.",
        f"// Source: the CPU authority's {AUTHORITY_MODULE} (SHA-256 {AUTHORITY_MODULE_SHA256}),",
        "// the Apple M4 reciprocal capture that src/csl/metal-division.js reads. Each",
        "// string below is one line of its base64 band bitstream, byte for byte.",
        '#include "noisemaker/metal_division.hpp"',
        "",
        "#include <iterator>",
        "#include <string_view>",
        "",
        "namespace noisemaker::metal {",
        "namespace {",
        "using namespace std::string_view_literals;",
        "constexpr std::string_view kBits[] = {",
    ]
    out.extend(f'    "{line}"sv,' for line in data["lines"])
    out.extend([
        "};",
        "}  // namespace",
        "",
        "const ReciprocalData& reciprocal_data() noexcept {",
        "  static constexpr ReciprocalData data{",
        f"      {data['bandLow']!r}, {data['bandHigh']!r}, {data['bandBits']}U, {data['positiveDeviations']}U, "
        f"{data['negativeDeviations']}U,",
        f'      "{data["tableSha256"]}"sv,',
        f'      "{data["bitsSha256"]}"sv,',
        f'      "{AUTHORITY_MODULE_SHA256}"sv,',
        "      kBits, std::size(kBits)};",
        "  return data;",
        "}",
        "",
        "}  // namespace noisemaker::metal",
        "",
    ])
    return "\n".join(out).encode("ascii")


def from_authority(cpu_root: pathlib.Path) -> bytes:
    module = cpu_root / AUTHORITY_MODULE
    text = module.read_bytes().decode("utf-8").replace("\r\n", "\n")
    digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
    if digest != AUTHORITY_MODULE_SHA256:
        raise DataError(f"{AUTHORITY_MODULE} sha256 {digest} is not the pinned capture {AUTHORITY_MODULE_SHA256}")
    return render(parse_module(text))


def verify_committed() -> None:
    """Recompute the bitstream digest of the committed file without the authority."""
    text = TARGET.read_text(encoding="ascii")
    lines = re.findall(r'^    "([A-Za-z0-9+/=]+)"sv,$', text, re.MULTILINE)
    recorded = re.findall(r'^      "([0-9a-f]{64})"sv,$', text, re.MULTILINE)
    if len(recorded) != 3 or recorded[2] != AUTHORITY_MODULE_SHA256:
        raise DataError(f"{TARGET.relative_to(ROOT)} does not record the pinned authority module")
    if hashlib.sha256("".join(lines).encode("ascii")).hexdigest() != recorded[1]:
        raise DataError(f"{TARGET.relative_to(ROOT)} bitstream does not match its recorded SHA-256")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--verify", action="store_true")
    parser.add_argument("--cpu-root", type=pathlib.Path)
    arguments = parser.parse_args(argv)
    try:
        if arguments.verify:
            verify_committed()
            print("metal reciprocal data: committed bitstream verified")
            return 0
        if arguments.cpu_root is None:
            parser.error("--write and --check need --cpu-root")
        generated = from_authority(arguments.cpu_root.resolve())
        if arguments.write:
            TARGET.write_bytes(generated)
            print(f"wrote {TARGET.relative_to(ROOT)}")
            return 0
        if TARGET.read_bytes() != generated:
            print(f"{TARGET.relative_to(ROOT)} differs from the authority capture", file=sys.stderr)
            return 1
        print("metal reciprocal data: ok")
        return 0
    except DataError as error:
        print(f"generate_metal_reciprocal_data: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
