#!/usr/bin/env python3
"""Fail-closed materializer for the Metal division and nearest-texel oracle.

Reads the checked-in, sha256-sidecar-verified
docs/port-engineering/metal-division-parity/metal-division-oracles.json
(produced by metal_division_oracle_generator.mjs from the unmodified CPU
authority) and writes tests/oracles/metal_division_expected.inc, which
tests/test_metal_division.cpp includes, so the native suite never runs node.

Usage:
  python3 -m tools.glslcpp.generate_metal_division_native_oracle_include --check
  python3 -m tools.glslcpp.generate_metal_division_native_oracle_include --write
"""
from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
PACKAGE = ROOT / "docs/port-engineering/metal-division-parity"
ORACLE = PACKAGE / "metal-division-oracles.json"
TARGET = ROOT / "tests/oracles/metal_division_expected.inc"
SCHEMA = "noisemaker-for-cpp.metal-division.v1"
# Frozen from the committed authority oracle. A recomputed adjacent sidecar
# cannot authorize a new baseline.
EXPECTED_ORACLE_SHA256 = "f8dae1197c55204094e4c4e127b1b73f3606b1f34a75ea9f2d2172c87c25afa5"
FLOAT = re.compile(r"^(?:[0-9a-f]{8}|nan)$")
DOUBLE = re.compile(r"^(?:[0-9a-f]{16}|nan)$")


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _load() -> dict:
    payload = ORACLE.read_bytes()
    sidecar = (ORACLE.parent / f"{ORACLE.name}.sha256").read_text(encoding="utf-8")
    if sidecar != f"{_sha256(payload)}  {ORACLE.name}\n":
        raise SystemExit("metal-division-oracles.json sidecar drift")
    if _sha256(payload) != EXPECTED_ORACLE_SHA256:
        raise SystemExit("metal-division-oracles.json frozen authority payload drift")
    document = json.loads(payload)
    if document.get("schema") != SCHEMA or document.get("exact") is not True or document.get("toleranceNone") is not True:
        raise SystemExit("oracle does not declare the exact zero-tolerance schema")
    return document


def _float(word: str) -> str:
    if not FLOAT.fullmatch(word):
        raise SystemExit(f"malformed float32 word {word!r}")
    return "kNan32" if word == "nan" else f"0x{word}u"


def _double(word: str) -> str:
    if not DOUBLE.fullmatch(word):
        raise SystemExit(f"malformed double word {word!r}")
    return "kNan64" if word == "nan" else f"0x{word}ull"


def render(document: dict) -> bytes:
    lines = [
        "// Generated by generate_metal_division_native_oracle_include.py; exact checked JSON authority.",
        "#pragma once",
        "#include <cstdint>",
        "namespace noisemaker_metal_division_oracle {",
        "// kNan32 / kNan64 mark a NaN result: any NaN matches it.",
        "inline constexpr std::uint32_t kNan32 = 0xffffffffu;",
        "inline constexpr std::uint64_t kNan64 = 0xffffffffffffffffull;",
        "struct Measured { std::uint32_t a, b, gpu; std::uint64_t result; };",
        "struct Pair { std::uint64_t a, b, result; };",
        "struct Reciprocal { std::uint64_t value, result; };",
        "struct Nearest { std::uint32_t width, height, u, v, column, row; };",
        f"inline constexpr Measured kMeasured[] = {{",
    ]
    lines.extend(f"  {{{_float(c['a'])}, {_float(c['b'])}, {_float(c['gpu'])}, {_double(c['result'])}}},"
                 for c in document["measured"])
    lines.append("};")
    lines.append("inline constexpr Pair kRandom[] = {")
    lines.extend(f"  {{{_double(c['a'])}, {_double(c['b'])}, {_double(c['result'])}}},"
                 for c in document["random"] if c["a"] != "nan" and c["b"] != "nan")
    lines.append("};")
    lines.append("inline constexpr Reciprocal kReciprocals[] = {")
    lines.extend(f"  {{{_double(c['value'])}, {_double(c['result'])}}}," for c in document["reciprocals"])
    lines.append("};")
    lines.append("inline constexpr Nearest kNearest[] = {")
    for c in document["nearest"]:
        lines.append(f"  {{{int(c['width'])}u, {int(c['height'])}u, {_float(c['u'])}, {_float(c['v'])}, "
                     f"{int(c['column'])}u, {int(c['row'])}u}},")
    lines.append("};")
    lines.append("}  // namespace noisemaker_metal_division_oracle")
    return ("\n".join(lines) + "\n").encode("ascii")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    arguments = parser.parse_args(argv)
    generated = render(_load())
    if arguments.write:
        TARGET.write_bytes(generated)
        TARGET.with_name(TARGET.name + ".sha256").write_text(f"{_sha256(generated)}  {TARGET.name}\n", encoding="utf-8")
        print(f"wrote {TARGET.relative_to(ROOT)}")
        return 0
    if TARGET.read_bytes() != generated:
        print(f"{TARGET.relative_to(ROOT)} is stale", file=sys.stderr)
        return 1
    print("metal division native oracle include: ok")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
