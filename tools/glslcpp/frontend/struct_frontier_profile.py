# --- walkers -----------------------------------------------------------------
#
# The census walkers below are the freeze-time walkers, verbatim: every
# re-derivation must visit the same nodes in the same order, or the census
# comparison is meaningless. Every function body and every top-level
# statement is walked with parent tracking so member roles (write / read /
# swizzle) re-derive exactly as they were measured.


def _walk_statements(value):
    yield value
    for child in value.children:
        yield from _walk_statements(child)


def _program_nodes(program: TypedProgram):
    """Every expression node in every function body, with its parent
    expression (or ``None``) and its enclosing top-level statement."""
    for function in program.functions:
        for statement in function.body:
            for node in _walk_statements(statement):
                for expression in node.expressions:
                    stack = [(expression, None)]
                    while stack:
                        current, parent = stack.pop()
                        yield function, node, current, parent
                        for child in current.children:
                            stack.append((child, current))


def _member_role(node, parent):
    """The measured role of a member node: an ``assign`` target writes,
    a ``swizzle`` parent reads lane-wise, everything else reads."""
    if parent is not None and parent.kind == "assign" and node is parent.children[0]:
        return "write"
    if parent is not None and parent.kind == "swizzle":
        return "swizzle"
    return "read"


def _derive_structs(program):
    return tuple(
        (item.id, item.name, item.type.display(), item.type.kind,
         _span(item), _sha(item),
         tuple((field.id, field.name, field.type.display(), _span(field),
                _sha(field))
               for field in item.fields))
        for item in program.structs)


def _derive_return_functions(program):
    return tuple(sorted(
        (item.id, item.name, item.return_type.display(), _span(item),
         _sha(item),
         tuple((parameter.id, parameter.name, parameter.type.display(),
                parameter.direction)
               for parameter in item.parameters))
        for item in program.functions if item.return_type.kind == "struct"))


def _derive_parameters(program):
    return tuple(sorted(
        (item.id, item.name, parameter.name, parameter.type.display(),
         parameter.direction)
        for item in program.functions for parameter in item.parameters
        if parameter.type.kind == "struct"))


def _derive_census(program):
    """Everything the frozen lock compares, in one pass over the tree."""
    locals_out = []
    members_out = []
    constructors = []
    total_nodes = 0
    total_assigns = 0
    for function, statement, item, parent in _program_nodes(program):
        total_nodes += 1
        if item.kind == "assign":
            total_assigns += 1
        if (item.kind == "declaration" and item.symbol is not None
                and item.symbol.type.kind == "struct"):
            record = [function.id, item.symbol.id, item.symbol.name,
                      item.symbol.type.display(), _span(item), _sha(item),
                      statement.kind, _span(statement), _sha(statement),
                      bool(item.children), item.symbol.storage]
            if item.children:
                initializer = item.children[0]
                record.append(initializer.kind)
                record.append(_span(initializer))
                record.append(_sha(initializer))
                if initializer.kind == "call":
                    record.append(initializer.callee)
                    record.append(initializer.signature_id)
            locals_out.append(tuple(record))
        if (item.kind == "member" and item.children
                and item.children[0].type.kind == "struct"):
            base = item.children[0]
            members_out.append((function.id, item.member,
                                base.symbol_id if base.kind == "id" else None,
                                base.kind, base.type.display(),
                                item.type.display(), _member_role(item, parent),
                                parent.kind if parent is not None else None,
                                _span(item), _sha(item)))
        if (item.kind == "construct" and item.constructor_type is not None
                and item.constructor_type.kind == "struct"):
            constructors.append((function.id, _span(item), _sha(item)))
    return (tuple(locals_out), tuple(members_out), tuple(constructors),
            total_nodes, total_assigns)


def _span_key(span_text: str):
    start = span_text.split("-")[0]
    line, column = start.split(":")
    return (int(line), int(column))


def _sort_census(locals_out, members_out):
    """The frozen ordering: locals by (statement span, declaration span),
    members by node span. The freeze ran the same sort."""
    return (tuple(sorted(locals_out, key=lambda item: (_span_key(item[7]),
                                                       _span_key(item[4])))),
            tuple(sorted(members_out, key=lambda item: _span_key(item[8]))))


def _profile_fail(profile: str, message: str) -> ValueError:
    return ValueError(f"{profile}: {message}")


class StructFrontierRecord(NamedTuple):
    """The authenticated struct plumbing of one carrier.

    ``structs`` is the live ``typed.structs`` tuple (the validator's
    declaration gate consumes it by identity), ``struct_types`` the live
    type objects (``reject_type``'s struct arm), ``locals`` /
    ``members`` the live plumbing nodes in frozen order, and ``consumed``
    every live object the authentication consumed, each exactly once.
    """

    structs: tuple
    struct_types: tuple
    locals: tuple
    members: tuple
    consumed: tuple


def authenticate_struct_frontier(
        program: TypedProgram, source_hash: str | None,
        profile: str | None) -> StructFrontierRecord | None:
    """Return the frozen struct-plumbing identity of ``program.key``.

    Returns ``None`` when the key is not a carrier and no profile was
    supplied; supplying a profile for a non-carrier key is a hard failure
    that names the five admitted declarations.
    """
    if program.key not in _LOCKS:
        if profile is not None:
            raise _profile_fail(
                SHAPES3D_PROFILE,
                "program key is not an admitted struct-frontier carrier; "
                f"{SHAPES3D_KEY} TransformData/ShapeParams, "
                f"{RENDER3D_KEY} and {RENDER_CUBE_KEY} VoxelHit/IsoHit, "
                f"{RENDER_LIT_KEY} IsoHit, {FLYTHROUGH_KEY} FractalResult "
                "are the sole admitted declarations")
        return None
    lock = _LOCKS[program.key]
    profile_name = PROFILES[program.key]

    def fail(message: str) -> ValueError:
        return _profile_fail(profile_name, message)

    if profile != profile_name:
        raise fail("exact profile carrier required")
    if source_hash != lock["raw_sha256"]:
        raise fail("exact caller source hash required")
    raw = program.raw_source.encode("utf-8")
    if (len(raw) != lock["raw_bytes"]
            or hashlib.sha256(raw).hexdigest() != lock["raw_sha256"]):
        raise fail("raw source drift")
    normalized = program.source.encode("utf-8")
    if (program.body_status != "analyzed"
            or len(normalized) != lock["normalized_bytes"]
            or hashlib.sha256(normalized).hexdigest()
            != lock["normalized_sha256"]):
        raise fail("normalized source drift")
    if tuple((item.name, item.kind, item.canonical_value)
             for item in program.preprocessor_defines) != lock["defines"]:
        raise fail("preprocessor define lock mismatch")
    if _sha(program.functions) != lock["functions_sha256"]:
        raise fail("typed function fingerprint drift")
    if _whole(program) != lock["whole_sha256"]:
        raise fail("whole-program fingerprint drift")
    if _interface(program) != lock["interface_sha256"]:
        raise fail("interface fingerprint drift")

    measured_structs = _derive_structs(program)
    if measured_structs != lock["structs"]:
        raise fail("struct declaration census mismatch")
    measured_returns = _derive_return_functions(program)
    if measured_returns != lock["return_functions"]:
        raise fail("struct-return function census mismatch")
    measured_parameters = _derive_parameters(program)
    if measured_parameters != lock["parameters"]:
        raise fail("struct-typed parameter census mismatch")
    measured_locals, measured_members, measured_constructors, \
        total_nodes, total_assigns = _derive_census(program)
    if measured_constructors:
        raise fail("struct constructor census mismatch: "
                   f"{measured_constructors!r}")
    if (total_nodes, total_assigns) != (lock["total_nodes"],
                                        lock["total_assigns"]):
        raise fail("whole-program node census mismatch")
    sorted_locals, sorted_members = _sort_census(measured_locals,
                                                 measured_members)
    if sorted_locals != lock["locals"]:
        raise fail(f"struct local census mismatch: {len(sorted_locals)}")
    if sorted_members != lock["members"]:
        raise fail(f"struct member census mismatch: {len(sorted_members)}")

    locals_by_symbol: dict[int, tuple] = {}
    for function, statement, item, _parent in _program_nodes(program):
        if (item.kind == "declaration" and item.symbol is not None
                and item.symbol.type.kind == "struct"):
            locals_by_symbol[item.symbol.id] = (
                function, item, item.symbol, statement)
    ordered_locals = tuple(
        locals_by_symbol[record[1]] for record in lock["locals"])
    ordered_members = tuple(
        next(item
             for function, _statement, item, _parent in
             _program_nodes(program)
             if item.kind == "member" and _span(item) == record[8]
             and _sha(item) == record[9])
        for record in lock["members"])

    consumed: list = []
    consumed.extend(program.structs)
    for item in program.structs:
        consumed.extend(item.fields)
    consumed.extend(item for item in program.functions
                    if item.return_type.kind == "struct")
    for _function, item, symbol, _statement in ordered_locals:
        consumed.append(item)
        consumed.append(symbol)
    consumed.extend(ordered_members)
    identities = [id(item) for item in consumed]
    if (len(identities) != lock["consumed"]
            or len(set(identities)) != len(identities)):
        raise fail("struct-frontier consumed-object ledger mismatch")
    return StructFrontierRecord(
        structs=tuple(program.structs),
        struct_types=tuple(item.type for item in program.structs),
        locals=ordered_locals,
        members=ordered_members,
        consumed=tuple(consumed))


def apply_struct_frontier(
        program: TypedProgram, source_hash: str | None,
        profile: str | None) -> TypedProgram:
    """Authenticate the frozen identity profile without changing the tree."""
    authenticate_struct_frontier(program, source_hash, profile)
    return program


def allowed_row_fields(key: str) -> frozenset[str]:
    """The complete set of slice-row fields permitted for ``key`` (an
    allowlist, enforced by the validator's ``set(item) != expected``
    comparison when a carrier promotes)."""
    fields = ALLOWED_ROW_FIELDS.get(key)
    if fields is None:
        raise _profile_fail(
            SHAPES3D_PROFILE,
            f"{key} is not an admitted struct-frontier carrier")
    return fields
