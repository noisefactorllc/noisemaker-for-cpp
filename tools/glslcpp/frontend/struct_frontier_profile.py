"""Exact-identity admission profile for the **struct-declaration frontier**
shared by five pending programs.

The counted-for queue's remaining 3D render/synth families all stop at the
same authentic validator frontier -- ``unsupported struct declaration`` --
measured this session against the live corpus
``e24c844f8dada85551ab084f41db8944fbc176c8`` with this repo's own
``parse_program``/``analyze_program`` (measure, never transcribe)::

    classicNoisedeck/shapes3d:shapes3d       54:1  TransformData + ShapeParams
    render/render3d:render3d                (113) VoxelHit + IsoHit
    render/renderCubemap3d:renderCubemap3d  (112) VoxelHit + IsoHit
    render/renderLit3d:renderLit3d          (190) IsoHit
    synth3d/flythrough3d:precompute         (172) FractalResult

(The diagnostic line names the FIRST declaration; the census below freezes
every struct the program declares.) The validator's struct gate admits
exactly one struct by object identity through
``struct_declaration_profile`` (newton/julia); these carriers need several
structs per program, member-write plumbing on uninitialized locals, and --
for shapes3d -- struct-typed function parameters. This module freezes the
complete struct plumbing of each carrier and admits it proof-gated:

* every struct declaration, its fields (id/name/type/span/node hash), and
  the ``typed.structs`` order itself must re-derive identically;
* every struct-returning function (signature incl. parameters, span, node
  hash) and every struct-typed parameter is frozen;
* every struct-typed local (uninitialized or call-initialized), its
  enclosing statement, and its initializer call are frozen;
* every ``member`` node over a struct-typed base, with its read/write/
  swizzle role and parent kind, is frozen in program order;
* struct **constructor** nodes are frozen ABSENT (these carriers default-
  declare their locals and fill them member by member -- a
  ``VoxelHit(...)`` anywhere is a hard failure, exactly like the newton
  module's absent-sets);
* struct-typed **globals** are frozen ABSENT (the corpus declares none).

Admission is by object identity into this module's frozen records only.
Nothing here touches ``APPROVED_CAPABILITIES`` or ``APPROVED_TYPES``; the
validator keeps every other program on the unchanged single-struct gate and
the emitter keeps every struct type rejected (this leg is a validator
advancement: after admission each carrier's probe frontier moves from
``typed.validator`` to the emitter's own struct-type diagnostic, which the
ratchet records -- no program promotes this pass and no generated artifact
moves).

Composition: all five carriers already carry loop proofs (const-global or
parameter-bound) and three carry ``cross-builtin-admission-v1``; the
fingerprints below are frozen over the **post-admission tree** -- exactly
the tree ``validate_capabilities`` authenticates -- so composing the
profiles binds one tree. ``authenticate_struct_frontier`` changes no node
(``apply_struct_frontier`` is the identity), so the cross profiles' frozen
hashes stay valid.

Fingerprint tiers: raw/normalized bytes+SHA-256, the typed functions
fingerprint, the whole-program fingerprint (``_whole`` includes the
attached ``counted_loop_proof`` and every profile field) and the interface
fingerprint. A source, define-profile, or proof-attachment drift turns the
carrier red instead of silently admitting a different tree.
"""

